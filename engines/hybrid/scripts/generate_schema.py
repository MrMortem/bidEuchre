#!/usr/bin/env python3
"""Generate shared constants from exact schema/rule bytes; --check never writes."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import pprint
import sys

RULE_PATHS = (
    "bid-euchre-final-rules.md",
    "src/BidEuchre.Core/Domain.cs",
    "src/BidEuchre.Core/GameRules.cs",
    "src/BidEuchre.Core/GameEngine.cs",
)


def validate_schema(schema: dict) -> None:
    """Reject incompatible v1 vocabulary, gaps, overlaps and nested widths."""
    cards = [rank + suit for suit in "CDHS" for rank in "9TJQKA"]
    actions = ["bestaction pass"]
    actions += ["bestaction bid " + bid for bid in ("3", "4", "5", "6", "partnersbest", "alone")]
    actions += ["bestaction contract high", "bestaction contract low"]
    actions += ["bestaction contract trump " + suit for suit in ("clubs", "diamonds", "hearts", "spades")]
    actions += ["bestaction exchange " + card for card in cards]
    actions += ["bestaction play " + card for card in cards]
    for key, expected in (("version", 1), ("feature_count", 1188), ("boundary_feature_count", 38),
                          ("action_count", 61), ("output_count", 165), ("card_codes", cards),
                          ("actions", actions)):
        if schema.get(key) != expected:
            raise ValueError(f"invalid v1 {key}")
    if schema["fingerprints"]["rule_paths"] != list(RULE_PATHS):
        raise ValueError("invalid ordered rule paths")

    def validate_fields(fields: list[dict], size: int) -> None:
        offset = 0
        names = set()
        for field in fields:
            if field["name"] in names or field["offset"] != offset or field["size"] <= 0:
                raise ValueError("duplicate field, gap or overlap in layout")
            names.add(field["name"])
            if "layout" in field:
                nested = schema["layouts"][field["layout"]]
                if nested["size"] * field["repeat"] != field["size"]:
                    raise ValueError("nested layout width mismatch")
            offset += field["size"]
        if offset != size:
            raise ValueError(f"layout width {offset} does not match {size}")

    for layout in schema["layouts"].values():
        validate_fields(layout["fields"], layout["size"])
    validate_fields(schema["main_blocks"], schema["feature_count"])
    validate_fields(schema["boundary_blocks"], schema["boundary_feature_count"])
    validate_fields(schema["output_heads"], schema["output_count"])


def rule_fingerprint(root: Path) -> str:
    digest = hashlib.sha256()
    for name in RULE_PATHS:
        digest.update(name.encode("utf-8") + b"\0" + (root / name).read_bytes() + b"\0")
    return digest.hexdigest()


def render(schema: dict, raw: bytes, root: Path) -> tuple[str, str]:
    schema_hash = hashlib.sha256(raw).hexdigest()
    rule_hash = rule_fingerprint(root)
    cpp = ["// Generated by scripts/generate_schema.py; do not edit.", "#pragma once", "",
           "#include <array>", "#include <cstddef>", "#include <string_view>", "",
           "namespace hybrid::schema {", "using namespace std::literals;",
           "struct Block { std::string_view name; std::size_t offset; std::size_t size; std::string_view layout; std::size_t repeat; };", ""]
    for name in ("version", "feature_count", "boundary_feature_count", "action_count", "output_count"):
        cpp.append(f"inline constexpr std::size_t {name} = {schema[name]};")
    cpp += [f'inline constexpr std::string_view schema_sha256 = "{schema_hash}";',
            f'inline constexpr std::string_view rule_sha256 = "{rule_hash}";']

    def strings(name: str, values: list[str]) -> None:
        encoded = ", ".join(json.dumps(value) + "sv" for value in values)
        cpp.append(f"inline constexpr std::array<std::string_view, {len(values)}> {name} = {{{encoded}}};")

    def blocks(name: str, values: list[dict]) -> None:
        cpp.append(f"inline constexpr std::array<Block, {len(values)}> {name} = {{{{")
        for value in values:
            cpp.append("    {" + f'{json.dumps(value["name"])}, {value["offset"]}, {value["size"]}, '
                       + f'{json.dumps(value.get("layout", ""))}, {value.get("repeat", 1)}' + "},")
        cpp.append("}};")
        for value in values:
            cpp.append(f'inline constexpr std::size_t {name}_{value["name"]}_offset = {value["offset"]};')
            cpp.append(f'inline constexpr std::size_t {name}_{value["name"]}_size = {value["size"]};')

    for name in ("card_codes", "suit_names", "rank_codes", "bid_names", "phases", "actions"):
        strings("action_commands" if name == "actions" else name, schema[name])
    strings("rule_paths", list(RULE_PATHS))
    for name in ("main_blocks", "boundary_blocks", "output_heads"):
        blocks(name, schema[name])
    for name, layout in schema["layouts"].items():
        cpp.append(f'inline constexpr std::size_t {name}_size = {layout["size"]};')
        blocks(name + "_fields", layout["fields"])
    for name, divisor in schema["normalization"].items():
        cpp.append(f"inline constexpr float {name}_divisor = {divisor}.0f;")
    cpp += ["} // namespace hybrid::schema", ""]
    python = ['"""Generated by scripts/generate_schema.py; do not edit."""', ""]
    for name in ("version", "feature_count", "boundary_feature_count", "action_count", "output_count"):
        python.append(f"{name.upper()} = {schema[name]}")
    python += [f"SCHEMA_SHA256 = {schema_hash!r}", f"RULE_SHA256 = {rule_hash!r}"]
    for name in ("card_codes", "suit_names", "rank_codes", "bid_names", "phases", "actions"):
        python.append(f'{"ACTION_COMMANDS" if name == "actions" else name.upper()} = {tuple(schema[name])!r}')
    for name in ("main_blocks", "boundary_blocks", "output_heads", "layouts", "normalization", "semantics", "fingerprints"):
        python.append(f"{name.upper()} = " + pprint.pformat(schema[name], sort_dicts=False, width=100))
    python.append("")
    return "\n".join(cpp), "\n".join(python)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are missing or stale")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[3], help="repository root")
    args = parser.parse_args()
    base = args.root / "engines/hybrid"
    try:
        raw = (base / "schema/observation-v1.json").read_bytes()
        schema = json.loads(raw)
        validate_schema(schema)
        cpp, python = render(schema, raw, args.root)
        outputs = ((base / "native/include/hybrid/schema.hpp", cpp),
                   (base / "python/hybrid_training/schema.py", python))
        stale = []
        for path, contents in outputs:
            expected = contents.encode("utf-8")
            if args.check:
                if not path.exists() or path.read_bytes() != expected:
                    stale.append(str(path))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(expected)
        if stale:
            print("stale generated schema: " + ", ".join(stale), file=sys.stderr)
            return 1
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"schema generation failed: {error}", file=sys.stderr)
        return 1
    print("Schema constants are current." if args.check else "Generated C++ and Python schema constants.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
